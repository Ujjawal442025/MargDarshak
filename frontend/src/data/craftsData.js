export function getCraftsForDistrict(districtName) {
  if (!districtName) return craftsCatalog.slice(0, 4);

  const normalized = districtName.toLowerCase().trim();

  const matched = craftsCatalog.filter(
    (c) =>
      c.district.toLowerCase().includes(normalized) ||
      normalized.includes(c.district.toLowerCase()) ||
      c.city.toLowerCase().includes(normalized),
  );

  return matched.length > 0 ? matched : craftsCatalog.slice(0, 4);
}
